const fs=require('node:fs'),ts=require('typescript'),assert=require('node:assert/strict');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,esModuleInterop:true}}).outputText,f);
const {schoolGuidance,schoolReportSections}=require('../components/kit/lib/school-guidance.ts');
const {schoolProfile}=require('../components/kit/data/baccalaureate.ts');
const {schoolSelection}=require('../components/kit/lib/school-selection.ts');
const codes=['R','I','A','S','E','C'];
const scores=patch=>codes.map(d=>({dimension:d,raw:patch[d]??10}));
const evidence=codes.map(d=>'intereses:dimension:'+d);
const careers=[{id:'software',name:'Ingeniería de Software',areaId:'tecnologia'},{id:'medicina',name:'Medicina',areaId:'salud'}];
const science=schoolGuidance(scores({I:25,R:15,S:20}),evidence,{},careers);
assert.equal(science.suggested,'ciencias');
assert(science.science.some(o=>o.careers.some(c=>c.id==='medicina')));
const technical=schoolGuidance(scores({R:25,I:15}),evidence,{baccalaureate:'tecnico',specialty:'Informática'},careers);
assert.equal(technical.suggested,'tecnico');
assert(technical.technical.some(o=>o.careers.some(c=>c.id==='software')));
assert.equal(technical.profile.specialty,'Informática');
const specific=schoolGuidance(scores({R:25,I:20}),evidence,{learningPreference:'aplicar'},[...careers,{id:'bio',name:'Bioingeniería',areaId:'ingenieria'},{id:'auto',name:'Ingeniería Automotriz',areaId:'ingenieria'}],[{optionId:'informatica',dimensionId:'I',value:20,min:15,max:25,reason:'Explora soporte informático según el criterio documentado.',evidence:['intereses:dimension:I']}]);
assert.deepEqual(specific.technical.find(o=>o.id==='informatica').careers.map(c=>c.id),['software']);
assert.deepEqual(specific.technical.find(o=>o.id==='automotriz').careers.map(c=>c.id),['auto']);
assert.equal(schoolGuidance(scores({R:25,I:25}),evidence).suggested,'ambas');
assert.equal(schoolGuidance(scores({R:25,I:15}),evidence,{learningPreference:'investigar'}).suggested,'tecnico');
assert.equal(schoolGuidance(scores({I:25,R:15}),evidence,{learningPreference:'aplicar'}).suggested,'ciencias');
assert.equal(schoolGuidance(scores({I:25,R:15}),evidence,{learningPreference:'ambas'}).suggested,'ciencias');
for(const baccalaureate of ['por-definir','ciencias','tecnico'])assert.equal(schoolGuidance(scores({I:25,R:15}),evidence,{baccalaureate}).suggested,'ciencias','Declared modality must not decide the recommendation');
for(const raw of [5,15,25]){
  const r=schoolGuidance(codes.map(d=>({dimension:d,raw})),evidence);
  assert.equal(r.suggested,'ambas');assert.equal(r.science.length+r.technical.length,0);
}
for(const invalid of [[],scores({I:NaN}),scores({R:26}),scores({}).slice(1)])assert.equal(schoolGuidance(invalid,evidence,{learningPreference:'aplicar'}).suggested,'pendiente');
const artistic=schoolGuidance(scores({A:25,I:20}),evidence,{learningPreference:'aplicar'});
assert(artistic.technical.some(o=>o.id==='diseno-multimedia'));
assert.equal(schoolProfile({}).baccalaureate,'por-definir');
assert.equal(schoolProfile({baccalaureate:'ciencias',specialty:'old'}).specialty,'');
assert.throws(()=>schoolProfile({baccalaureate:'invalid'}));
assert.throws(()=>schoolProfile({learningPreference:'invalid'}));
assert.throws(()=>schoolProfile({specialty:'x'.repeat(141)}));
assert.throws(()=>schoolProfile({stage:{}}));
const sections=schoolReportSections(technical);
for(const pathway of [science,technical]){
 const raw=JSON.stringify(pathway),selected=schoolSelection(pathway);
 assert.equal(selected.modality,pathway.suggested);
 assert.deepEqual(selected.options,pathway.suggested==='tecnico'?pathway.technical:pathway.science);
 const visibleCount=selected.options.length===1?'Se muestra 1 '+(selected.modality==='tecnico'?'figura':'área'):'Se muestran '+selected.options.length+(selected.modality==='tecnico'?' figuras':' áreas');
 assert(selected.rankingNote.includes(visibleCount),'The displayed count belongs only to the selected modality');
 assert.equal(JSON.stringify(pathway),raw,'Selecting a modality never mutates stored evidence');
 assert.equal(schoolReportSections(pathway).filter(section=>/recomendadas/.test(section.title)).length,1);
 assert.deepEqual(schoolSelection(pathway,false).options,[],'Unpublished or incomplete evidence cannot unlock a modality');
}
const tied=schoolGuidance(scores({R:25,I:25}),evidence),tiedSelection=schoolSelection(tied);
assert.equal(tiedSelection.modality,null,'Tied interests do not invent a winning modality');
assert.equal(tiedSelection.comparison,true);
assert.equal(tiedSelection.title,'Explora Ciencias y Técnico');
assert.deepEqual(tiedSelection.options,[...tied.science,...tied.technical],'A modality tie retains the concrete options supported by interests');
assert.equal(tiedSelection.groups.length,2);
assert(tiedSelection.options.length>0&&tiedSelection.options.every(option=>option.evidence.length>0));
assert.equal(schoolReportSections(tied).filter(section=>/para explorar/.test(section.title)).length,2);
assert.deepEqual(schoolSelection(tied,false).options,[],'A tie cannot bypass completion and publication');
assert.deepEqual(schoolSelection(schoolGuidance(scores({R:15,I:15,A:15,S:15,E:15,C:15}),evidence)).options,[],'An entirely undifferentiated profile still does not invent specific options');
for(const suggested of ['pendiente',undefined,'unexpected']){
 const legacy={...technical,suggested};
 assert.equal(schoolSelection(legacy).modality,null);
 assert.equal(schoolSelection(legacy).title,'Modalidad por definir');
 assert.deepEqual(schoolSelection(legacy).options,[]);
 assert.equal(schoolSelection(legacy).rankingNote,null,'An unresolved modality cannot claim to show ranked options');
 assert.equal(schoolReportSections(legacy).filter(section=>/recomendadas/.test(section.title)).length,0);
}
assert(sections[0].title.includes('perfil'));
assert(sections.some(s=>s.lines.some(l=>l.includes('Ingeniería de Software'))));
assert(sections.at(-1).lines.some(l=>l.includes('requisitos')));
console.log('PASS school pathway: Ciencias, Técnico, ties, low/absent data, declared preferences, artistic technical routes, university links, profile validation and PDF sections.');
